import { fileURLToPath } from 'node:url';
import { mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { createApp } from '../dist/server/app.js';
import { CloudClient } from '../dist/server/cloud.js';
const dataDir = await mkdtemp(join(tmpdir(), 'kagemiyura-ui-'));
let calls = 0;
const server = createApp({dataDir, publicDir: fileURLToPath(new URL('../dist/public', import.meta.url)), instanceId: 'ui-smoke', cloud: new CloudClient(async () => { calls++; return new Response('data: {"choices":[{"delta":{"content":"Хозяин, переписка сохранена."}}]}\n\ndata: [DONE]\n\n'); })});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
let browser;
try {
 browser = await chromium.launch({headless:true,args:['--no-sandbox']});
 const page = await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
 const errors=[];
 page.on('pageerror', error => errors.push(error.message));
 const base=`http://127.0.0.1:${server.address().port}`;
 await page.goto(base+'/history');
 await page.waitForFunction(()=>!document.querySelector('#send').disabled);
 await page.locator('#history-empty').waitFor({state:'visible'});
 await page.goto(base+'/settings');
 await page.locator('#send').waitFor({state:'attached'});
 await page.locator('#api-key').fill('fake-key-local-test');
 await page.locator('#model').fill('mock/chat');
 await page.locator('#settings-form button[type=submit]').click();
 await page.getByText('Настройки сохранены.',{exact:true}).waitFor();
 assert.equal(await page.locator('[data-nav=chat]').count(),0);
 await page.locator('#avatar').click();
 assert.equal(await page.locator('#avatar').getAttribute('aria-expanded'),'true');
 await page.locator('#close-chat').click();
 await page.locator('#chat-page').waitFor({state:'hidden'});
 assert.equal(new URL(page.url()).pathname,'/settings');
 await page.locator('#avatar').click();
 await page.locator('#prompt').fill('Помни мой проект');
 await page.locator('#send').click();
 await page.getByText('Хозяин, переписка сохранена.',{exact:true}).waitFor();
 await page.waitForFunction(()=>!document.querySelector('#send').disabled);
 await page.reload();
 await page.getByText('Хозяин, переписка сохранена.',{exact:true}).waitFor();
 await page.locator('#new-chat').click();
 await page.locator('#welcome').waitFor({state:'visible'});
 await page.locator('#close-chat').click();
 await page.locator('[data-nav=history]').click();
 await page.locator('#history-search').fill('ПОМНИ');
 await page.locator('.conversation-row').waitFor();
 await page.locator('.conversation-row').click();
 await page.getByText('Хозяин, переписка сохранена.',{exact:true}).waitFor();
 page.once('dialog', d=>d.accept('Мой сохранённый проект'));
 await page.locator('#rename-chat').click();
 await page.locator('#conversation-title').filter({hasText:'Мой сохранённый проект'}).waitFor();
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#export-chat').click();
 const download=await downloadPromise;
 assert.match(download.suggestedFilename(),/^Kagemiyura-.*\.json$/);
 await mkdir(new URL('../.runtime',import.meta.url),{recursive:true});
 await page.screenshot({path:fileURLToPath(new URL('../.runtime/ui-desktop.png',import.meta.url))});
 await page.setViewportSize({width:390,height:844});
 for(const path of ['/chat','/history','/settings']) {
   await page.goto(base+path);
   await page.waitForFunction(()=>!document.querySelector('#send').disabled);
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,path+' overflows');
 }
 await page.locator('#avatar').click();
 await page.locator('#chat-page').waitFor({state:'visible'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile avatar chat overflows');
 await page.screenshot({path:fileURLToPath(new URL('../.runtime/ui-mobile.png',import.meta.url))});
 assert.deepEqual(errors,[]);
 assert.equal(calls,1,'Only the explicit chat should contact Cloud.ru');
 console.log('UI passed: chat, save/reload, new chat, history/search/open, rename, export, mobile pages, no browser errors; cloud calls: '+calls);
} finally {
 await browser?.close();
 server.closeAllConnections();
 await new Promise(resolve=>server.close(resolve));
 await rm(dataDir,{recursive:true,force:true,maxRetries:5});
}
